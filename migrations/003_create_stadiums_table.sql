CREATE TABLE stadiums (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    manager_id INT UNSIGNED NULL,
    address_id INT UNSIGNED NOT NULL,
    name VARCHAR(120) NOT NULL,
    description TEXT NULL,
    sport_type ENUM('football','futsal','basketball','volleyball','tennis','padel','multi_sport') NOT NULL,
    surface_type ENUM('natural_grass','artificial_turf','hard_court','wooden','sand') NOT NULL,
    capacity SMALLINT UNSIGNED NOT NULL,
    price_per_hour DECIMAL(10,3) NOT NULL,
    price_per_day DECIMAL(10,3) NULL,
    opening_time TIME NOT NULL,
    closing_time TIME NOT NULL,
    slot_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 60,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    created_by INT UNSIGNED NULL,
    updated_by INT UNSIGNED NULL,
    deleted_at DATETIME NULL,
    deleted_by INT UNSIGNED NULL,
    UNIQUE KEY uq_stadiums_code (code),
    UNIQUE KEY uq_stadiums_address (address_id),
    KEY ix_stadiums_manager (manager_id),
    KEY ix_stadiums_sport_active (sport_type, is_active),
    KEY ix_stadiums_deleted (deleted_at),
    CONSTRAINT fk_stadiums_manager FOREIGN KEY (manager_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_stadiums_address FOREIGN KEY (address_id) REFERENCES addresses (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
