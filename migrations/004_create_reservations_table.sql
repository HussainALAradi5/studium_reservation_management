CREATE TABLE reservations (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    stadium_id INT UNSIGNED NOT NULL,
    customer_id INT UNSIGNED NOT NULL,
    start_at DATETIME NOT NULL,
    end_at DATETIME NOT NULL,
    booking_unit ENUM('hour','day') NOT NULL DEFAULT 'hour',
    unit_count DECIMAL(6,2) NOT NULL,
    unit_price DECIMAL(10,3) NOT NULL,
    duration_minutes INT UNSIGNED NOT NULL,
    total_amount DECIMAL(10,3) NOT NULL,
    paid_amount DECIMAL(10,3) NOT NULL DEFAULT 0,
    status ENUM('pending','confirmed','completed','rejected','cancelled') NOT NULL DEFAULT 'pending',
    payment_status ENUM('unpaid','partial','paid','refunded') NOT NULL DEFAULT 'unpaid',
    notes VARCHAR(500) NULL,
    status_reason VARCHAR(255) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    created_by INT UNSIGNED NULL,
    updated_by INT UNSIGNED NULL,
    deleted_at DATETIME NULL,
    deleted_by INT UNSIGNED NULL,
    UNIQUE KEY uq_reservations_code (code),
    KEY ix_reservations_overlap (stadium_id, status, start_at, end_at),
    KEY ix_reservations_customer (customer_id, start_at),
    KEY ix_reservations_status_start (status, start_at),
    KEY ix_reservations_deleted (deleted_at),
    CONSTRAINT fk_reservations_stadium FOREIGN KEY (stadium_id) REFERENCES stadiums (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_customer FOREIGN KEY (customer_id) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
